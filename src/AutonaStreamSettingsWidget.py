class AutonaStreamSettingsWidget(QDockWidget):
    """配信設定 — everything scoped to the broadcast, not to the tournament.

    Stream destination, stream title, the stream org's own icon / thumbnail,
    and the YouTube thumbnail generator that consumes them. Kept apart from
    the EVENT tab (tournament-scoped: name, date, venue, tournament icon /
    banner) and from the SCORE tab (match-scoped, and gated behind 反映) so
    each panel owns one level of the data hierarchy.

    State lives under the `stream.*` subtree — ungated and board-agnostic.

    Since ADR-005 S4d the operations are core's (`core/StreamService.py`):
    the title's auto-generation, the channels, the org assets, the
    thumbnail generator and its options. This page asks for them and draws
    the state (`stream.*`) and the saved options; the dialogs, the file
    picker, the previews and the clipboard are what is left here. The title
    is generated whether or not this page is ever built.
    """

    def __init__(self, *args):
        super().__init__(*args)

        uic.loadUi(AutonaResolve("src/layout/AutonaStreamSettings.ui"), self)

        # Wrap the dock contents in a QScrollArea so the panel doesn't force
        # the whole window to grow vertically (same as the EVENT tab).
        self._contents = self.widget()
        self._contents.layout().setContentsMargins(
            UI.PANEL_MARGIN, UI.PANEL_MARGIN, UI.PANEL_MARGIN, UI.PANEL_MARGIN)
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setWidget(self._contents)
        self.setWidget(scroll)

        # NOTE: this panel is built on first reveal (startup Step 4b-3), so
        # the state it used to seed here is seeded at launch
        # (StateSchema.SeedPanelState) and the title is generated by
        # core (StreamService), panel or not.

        # State -> widgets (_RenderFromState): one pass queued at a time,
        # out of the notification (which runs inside StateManager.lock).
        self._renderPending = False

        self._buildStreamDestination()
        self._buildStreamTitle()
        self._buildOrgMedia()
        self._buildStreamThumbnail()

        # Normalise card padding / spacing across all top-level groups.
        for group in self.findChildren(QGroupBox):
            L.apply_card_layout(group)

        StateManagerBridge.instance.state_updated.connect(self._onStateUpdated)
        StateManagerBridge.instance.state_big_change.connect(
            self._QueueRender)

    # ---- state -> widgets ----

    def _onStateUpdated(self, _payload):
        self._QueueRender()

    def _QueueRender(self):
        if self._renderPending:
            return
        self._renderPending = True
        QTimer.singleShot(0, self, self._RenderFromState)

    def _RenderFromState(self):
        self._renderPending = False
        self._syncStreamDestinationCombo()
        self._renderTitle()
        self._renderOrgMedia()
        self._renderThumbnail()

    # ---- 配信先 ----

    def _buildStreamDestination(self):
        self.streamUrlCombo: QComboBox = self.findChild(
            QComboBox, "streamUrlCombo")
        self.btEditStreamChannel: QPushButton = self.findChild(
            QPushButton, "btEditStreamChannel")
        self.btAddStreamChannel: QPushButton = self.findChild(
            QPushButton, "btAddStreamChannel")

        self.btEditStreamChannel.clicked.connect(self._editStreamChannel)
        self.btAddStreamChannel.clicked.connect(self._addStreamChannel)

        # Populate and wire the combo only once every widget the handlers
        # touch exists — _onStreamChannelChanged reaches for the edit button.
        self._loadStreamChannels()
        self.streamUrlCombo.currentIndexChanged.connect(
            self._onStreamChannelChanged)
        self.streamUrlCombo.lineEdit().editingFinished.connect(
            self._onStreamChannelChanged)

        # Restore the saved selection rather than exporting the combo's empty
        # default — stream.url is persisted (user_data/state.json), so the
        # destination outlives the session.
        self._syncStreamDestinationCombo()
        self._updateEditStreamChannelBtn()

    def _loadStreamChannels(self):
        """Populate the stream URL combo from the saved channels."""
        with QSignalBlocker(self.streamUrlCombo):
            self.streamUrlCombo.clear()
            self.streamUrlCombo.addItem("", "")  # empty default
            for channel in StreamService.instance.Channels():
                self.streamUrlCombo.addItem(channel["name"], channel["url"])

    def _currentStreamUrl(self):
        # Row 0 carries empty data, so a free-typed URL falls through to the
        # combo's edit text.
        return self.streamUrlCombo.currentData() or self.streamUrlCombo.currentText()

    def _onStreamChannelChanged(self, *args):
        # SetStreamUrl carries the "only write when it changed" guard that
        # used to sit here (headless core Step 5).
        AutonaActions.instance.SetStreamUrl(self._currentStreamUrl())
        self._updateEditStreamChannelBtn()

    def _updateEditStreamChannelBtn(self):
        # Editing only applies to a saved channel — row 0 is the empty
        # default and free-typed text has no saved entry behind it.
        self.btEditStreamChannel.setEnabled(
            self.streamUrlCombo.currentIndex() > 0)

    def _syncStreamDestinationCombo(self, force=False):
        """Point the combo at the persisted stream.url without re-emitting.
        `force`: also while the combo has the focus (right after this page's
        own channel edit, which reloaded its rows)."""
        url = StateManager.Get(stream.URL_PATH, "") or ""
        combo = self.streamUrlCombo
        # Don't fight an edit in progress. The combo is editable, so its line
        # edit is the focus proxy and hasFocus() covers both.
        if (combo.hasFocus() and not force) or self._currentStreamUrl() == url:
            return
        with QSignalBlocker(combo):
            index = combo.findData(url)
            if index >= 0:
                combo.setCurrentIndex(index)
                # setCurrentIndex is a no-op when that row is already current,
                # which would strand stale free-typed text in the line edit.
                combo.setEditText(combo.itemText(index))
            else:
                # A URL typed straight into the combo has no saved row.
                combo.setCurrentIndex(0)
                combo.setEditText(url)
        self._updateEditStreamChannelBtn()

    def _promptStreamChannel(self, title, name="", url="", allowDelete=False):
        """Show the name/URL form dialog shared by the add and edit flows.
        Returns ("save", name, url), ("delete", None, None), or None when
        cancelled."""
        dialog = QDialog(self)
        dialog.setWindowTitle(title)
        dialog.setMinimumWidth(350)
        layout = QFormLayout(dialog)

        nameEdit = QLineEdit(name)
        nameEdit.setPlaceholderText("BST Stream")
        layout.addRow(QApplication.translate("app", "Channel name"), nameEdit)

        urlEdit = QLineEdit(url)
        urlEdit.setPlaceholderText("https://www.youtube.com/@B_ST_Stream/live")
        layout.addRow("URL", urlEdit)

        buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Ok | QDialogButtonBox.StandardButton.Cancel)

        result = {"action": None}

        def tryAccept():
            # Reject empty input with a warning instead of silently discarding
            # the entry after the dialog closes.
            if not nameEdit.text().strip() or not urlEdit.text().strip():
                QMessageBox.warning(
                    dialog,
                    QApplication.translate("app", "Input required"),
                    QApplication.translate(
                        "app", "Please enter both the channel name and URL."))
                return
            result["action"] = "save"
            dialog.accept()

        buttons.accepted.connect(tryAccept)
        buttons.rejected.connect(dialog.reject)

        if allowDelete:
            # DestructiveRole emits neither accepted nor rejected, so the
            # confirm handler below fully owns closing the dialog.
            deleteBtn = buttons.addButton(
                QApplication.translate("app", "Delete"),
                QDialogButtonBox.ButtonRole.DestructiveRole)

            def onDelete():
                reply = QMessageBox.question(
                    dialog,
                    QApplication.translate("app", "Delete stream channel"),
                    QApplication.translate(
                        "app", "Delete this stream channel?"),
                    QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
                    QMessageBox.StandardButton.No)
                if reply == QMessageBox.StandardButton.Yes:
                    result["action"] = "delete"
                    dialog.accept()

            deleteBtn.clicked.connect(onDelete)

        layout.addRow(buttons)

        if dialog.exec() != QDialog.DialogCode.Accepted or result["action"] is None:
            return None
        if result["action"] == "delete":
            return ("delete", None, None)
        return ("save", nameEdit.text().strip(), urlEdit.text().strip())

    def _addStreamChannel(self):
        result = self._promptStreamChannel(
            QApplication.translate("app", "Add stream channel"))
        if result is None:
            return
        _, name, url = result
        index = StreamService.instance.AddChannel(name, url)
        if index is None:
            return
        self._loadStreamChannels()
        # Select the newly added channel (emits, exporting the URL).
        self.streamUrlCombo.setCurrentIndex(index + 1)

    def _editStreamChannel(self):
        idx = self.streamUrlCombo.currentIndex() - 1  # row 0 is the empty default
        channels = StreamService.instance.Channels()
        if not (0 <= idx < len(channels)):
            return
        result = self._promptStreamChannel(
            QApplication.translate("app", "Edit stream channel"),
            name=channels[idx]["name"],
            url=channels[idx]["url"],
            allowDelete=True)
        if result is None:
            return
        action, name, url = result
        # The destination follows the channel (cleared with it, or moved to
        # its new URL): core's rule, so the Web's edits keep it too.
        if action == "delete":
            StreamService.instance.DeleteChannel(idx)
        else:
            StreamService.instance.UpdateChannel(idx, name, url)
        self._loadStreamChannels()
        self._syncStreamDestinationCombo(force=True)
        self._updateEditStreamChannelBtn()

    # ---- 配信タイトル ----

    def _buildStreamTitle(self):
        self.streamTitleEdit: QLineEdit = self.findChild(
            QLineEdit, "streamTitleEdit")
        self.btCopyStreamTitle: QPushButton = self.findChild(
            QPushButton, "btCopyStreamTitle")
        self.btCopyStreamTitle.clicked.connect(self.CopyStreamTitle)

        # The field draws stream.title, which core regenerates from the
        # tournament (StreamService); what the operator types is written on
        # finishing, and core keeps it until they clear the field. A render
        # never redraws the field while the operator is in it. On leaving,
        # core's rule decides whether the typing is written
        # (StreamService.TypedTitleWins): it is, over an auto title that
        # landed meanwhile (the generator never beats a hand), but not over
        # another writer's title, and an old value the field merely kept is
        # never written back.
        # What the field last showed in step with the state.
        self._titleShown = ""
        self.streamTitleEdit.editingFinished.connect(self._onTitleEdited)
        self._renderTitle()

    def _renderTitle(self):
        title = StateManager.Get(stream.TITLE_PATH, "") or ""
        edit = self.streamTitleEdit
        if edit.text() != title:
            if edit.hasFocus():
                # Decided once the operator leaves it (_onTitleEdited).
                return
            with QSignalBlocker(edit):
                edit.setText(title)
        self._titleShown = title

    def _onTitleEdited(self):
        text = self.streamTitleEdit.text()
        if stream.TypedTitleWins(
                text, self._titleShown,
                StateManager.Get(stream.TITLE_PATH, ""),
                StateManager.Get(stream.TITLE_AUTO_PATH)):
            AutonaActions.instance.SetStreamTitle(text)
            self._titleShown = text
        # Deferred: editingFinished runs inside the focus change, and the
        # field shows the state once it has been left.
        QTimer.singleShot(0, self, self._renderTitle)

    def CopyStreamTitle(self):
        title = self.streamTitleEdit.text().strip()
        if not title:
            return
        QApplication.clipboard().setText(title)

    # ---- 配信団体アイコン / サムネイル ----

    def _buildOrgMedia(self):
        self.orgIconView: QLabel = self.findChild(QLabel, "orgIconView")
        L.apply_media_preview(self.orgIconView)
        self.orgThumbView: QLabel = self.findChild(QLabel, "orgThumbView")
        L.apply_media_preview(self.orgThumbView)

        self.btLoadOrgIcon: QPushButton = self.findChild(
            QPushButton, "btLoadOrgIcon")
        self.btLoadOrgIcon.clicked.connect(self.LoadOrgIcon)

        self.btLoadOrgThumb: QPushButton = self.findChild(
            QPushButton, "btLoadOrgThumb")
        self.btLoadOrgThumb.clicked.connect(self.LoadOrgThumbnail)

        # Tagged danger: it discards both registered assets at once. Unlike
        # the tournament icon / banner there is no bundled default to fall
        # back to — the org assets are opt-in, so reset means "unregister".
        self.btResetOrgMedia: QPushButton = self.findChild(
            QPushButton, "btResetOrgMedia")
        L.tag_button(self.btResetOrgMedia, L.BUTTON_DANGER)
        self.btResetOrgMedia.clicked.connect(self.ResetOrgMedia)

        # The versions the previews were last drawn for: they are redrawn
        # when an import / a reset (here or on the Web) publishes new ones.
        self._shownOrgVersions = None
        self._renderOrgMedia()

    def _ImportOrgAsset(self, kind):
        """Prompt for an image and hand its bytes to core, which scales it
        down and saves it (StreamService.ImportOrgAsset)."""
        fileName = QFileDialog.getOpenFileName(
            self,
            QApplication.translate("app", "Open Image"),
            ".",
            QApplication.translate(
                "app", "Image Files") + " (*.png *.jpg *.bmp)"
        )[0]
        if not fileName:
            return
        try:
            data = Path(fileName).read_bytes()
        except OSError:
            logger.error(traceback.format_exc())
            data = b""
        result = StreamService.instance.ImportOrgAsset(kind, data)
        if result == stream.IMPORTED:
            self._renderOrgMedia(force=True)
            return
        if result == stream.SAVE_FAILED:
            message = QApplication.translate(
                "app", "画像を保存できませんでした。ほかのアプリがファイルを"
                "開いていないか確認してください。")
        else:
            message = QApplication.translate(
                "app", "画像を読み込めませんでした。PNG / JPEG / BMP"
                "（5000 万画素まで）の画像を選んでください。")
        QMessageBox.warning(
            self, QApplication.translate("app", "Warning"), message)

    def LoadOrgIcon(self):
        self._ImportOrgAsset("icon")

    def LoadOrgThumbnail(self):
        self._ImportOrgAsset("thumbnail")

    def _renderOrgMedia(self, force=False):
        versions = (StateManager.Get("stream.orgIconVersion", 0),
                    StateManager.Get("stream.orgThumbVersion", 0))
        if versions == self._shownOrgVersions and not force:
            return
        self._shownOrgVersions = versions
        self._showPreview(self.orgIconView, schema.STREAM_ORG_ICON_PATH,
                          60, 60)
        self._showPreview(self.orgThumbView, schema.STREAM_ORG_THUMB_PATH,
                          160, 90)

    @staticmethod
    def _showPreview(view, path, width, height):
        pix = QPixmap(path) if os.path.exists(path) else QPixmap()
        if pix.isNull():
            view.setPixmap(QPixmap())
            view.setText(QApplication.translate("app", "未登録"))
        else:
            view.setText("")
            view.setPixmap(pix.scaled(
                width, height,
                Qt.AspectRatioMode.KeepAspectRatio,
                Qt.TransformationMode.SmoothTransformation))

    def ResetOrgMedia(self):
        reply = QMessageBox.question(
            self,
            QApplication.translate("app", "Confirm"),
            QApplication.translate(
                "app", "登録した配信団体のアイコンとサムネイルを削除します。よろしいですか？"),
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
            QMessageBox.StandardButton.No)
        if reply != QMessageBox.StandardButton.Yes:
            return
        # Core also moves a thumbnail made from the org thumbnail back to
        # the tournament banner, so generation doesn't silently produce
        # nothing.
        StreamService.instance.ResetOrgAssets()
        self._renderOrgMedia(force=True)
        self._renderThumbnailOptions()

    # ---- 配信サムネイル生成 ----

    def _buildStreamThumbnail(self):
        self.rbStreamThumbSourceBanner: QRadioButton = self.findChild(
            QRadioButton, "rbStreamThumbSourceBanner")
        self.rbStreamThumbSourceOrg: QRadioButton = self.findChild(
            QRadioButton, "rbStreamThumbSourceOrg")
        self.rbStreamThumbCenter: QRadioButton = self.findChild(
            QRadioButton, "rbStreamThumbCenter")
        self.rbStreamThumbNetflix: QRadioButton = self.findChild(
            QRadioButton, "rbStreamThumbNetflix")
        self.cbStreamThumbOverlayOrgIcon: QCheckBox = self.findChild(
            QCheckBox, "cbStreamThumbOverlayOrgIcon")

        # The four radios share a parent widget in the .ui, so Qt's
        # auto-exclusivity made them one group of four: picking a style
        # unchecked the source and the other way round. One group per
        # option (a button in a QButtonGroup is exclusive within the group
        # only).
        self._thumbSourceGroup = QButtonGroup(self)
        self._thumbSourceGroup.addButton(self.rbStreamThumbSourceBanner)
        self._thumbSourceGroup.addButton(self.rbStreamThumbSourceOrg)
        self._thumbStyleGroup = QButtonGroup(self)
        self._thumbStyleGroup.addButton(self.rbStreamThumbCenter)
        self._thumbStyleGroup.addButton(self.rbStreamThumbNetflix)

        # The options are saved (settings.json, core): drawn from there and
        # saved on every change. The second radio of each pair toggles
        # whenever its pair changes, so it alone carries the choice.
        self._renderThumbnailOptions()
        self.rbStreamThumbSourceOrg.toggled.connect(
            self._onThumbSourceToggled)
        self.rbStreamThumbNetflix.toggled.connect(self._onThumbStyleToggled)
        self.cbStreamThumbOverlayOrgIcon.toggled.connect(
            self._onThumbOverlayToggled)

        self.btGenerateStreamThumbnail: QPushButton = self.findChild(
            QPushButton, "btGenerateStreamThumbnail")
        L.tag_button(self.btGenerateStreamThumbnail, L.BUTTON_SECONDARY)
        self.btGenerateStreamThumbnail.clicked.connect(
            self.GenerateStreamThumbnail)

        self.btCopyStreamThumbnail: QPushButton = self.findChild(
            QPushButton, "btCopyStreamThumbnail")
        self.btCopyStreamThumbnail.clicked.connect(self.CopyStreamThumbnail)
        # The run whose thumbnail the copy button asked for while none was
        # there yet: copied once that run is done (None: nothing waits).
        self._copyRevision = None

        self.streamThumbPreview: QLabel = self.findChild(
            QLabel, "streamThumbPreview")
        # The .ui pins this slot to 160×90 via maximumSize — don't pass
        # min_* here or Qt resolves min>max in favour of min and the
        # label balloons to the requested minimum.
        L.apply_media_preview(self.streamThumbPreview)
        self.streamThumbPath: QLabel = self.findChild(QLabel, "streamThumbPath")

        # What stream.thumbnail held when it was last drawn.
        self._shownThumbnail = None
        self._renderThumbnail()

    def _renderThumbnailOptions(self):
        options = StreamService.instance.ThumbnailOptions()
        org = options["source"] == "org"
        netflix = options["style"] == "netflix"
        # Every button blocked: checking one unchecks its partner, whose
        # toggled() would save the option back.
        blockers = [QSignalBlocker(button) for button in (
            *self._thumbSourceGroup.buttons(),
            *self._thumbStyleGroup.buttons(),
            self.cbStreamThumbOverlayOrgIcon)]
        try:
            (self.rbStreamThumbSourceOrg if org
             else self.rbStreamThumbSourceBanner).setChecked(True)
            (self.rbStreamThumbNetflix if netflix
             else self.rbStreamThumbCenter).setChecked(True)
            self.cbStreamThumbOverlayOrgIcon.setChecked(
                options["overlayOrgIcon"])
        finally:
            for blocker in blockers:
                blocker.unblock()

    def _onThumbSourceToggled(self, checked):
        StreamService.instance.SetThumbnailOptions(
            {"source": "org" if checked else "banner"})

    def _onThumbStyleToggled(self, checked):
        StreamService.instance.SetThumbnailOptions(
            {"style": "netflix" if checked else "center"})

    def _onThumbOverlayToggled(self, checked):
        StreamService.instance.SetThumbnailOptions(
            {"overlayOrgIcon": bool(checked)})

    def GenerateStreamThumbnail(self):
        # A job of core's; stream.thumbnail reports it (_renderThumbnail).
        if StreamService.instance.GenerateThumbnail() == stream.BUSY:
            self.streamThumbPath.setText(QApplication.translate(
                "app", "サムネイルを生成しています…"))

    def _thumbnailState(self):
        thumbnail = StateManager.Get(stream.THUMBNAIL_PATH)
        if not isinstance(thumbnail, dict):
            thumbnail = schema.DefaultStreamThumbnail()
        return (thumbnail.get("status", stream.IDLE),
                thumbnail.get("path", "") or "",
                thumbnail.get("error", "") or "",
                thumbnail.get("revision", 0))

    def _renderThumbnail(self):
        shown = self._thumbnailState()
        if shown == self._shownThumbnail:
            return
        previous = self._shownThumbnail
        self._shownThumbnail = shown
        status, path, error, revision = shown

        self.btGenerateStreamThumbnail.setEnabled(status != stream.RUNNING)

        # A new run may reuse the file name (same second): the revision
        # tells it apart.
        if previous is None or (path, revision) != (previous[1], previous[3]):
            self._showThumbnailPreview(path)

        if status == stream.RUNNING:
            self.streamThumbPath.setText(QApplication.translate(
                "app", "サムネイルを生成しています…"))
        elif status == stream.DONE:
            self.streamThumbPath.setText(
                QApplication.translate("app", "Saved: ") + path)
        elif status == stream.ERROR:
            self.streamThumbPath.setText(self._thumbnailErrorText(error))
        else:
            self.streamThumbPath.setText("")

        if self._copyRevision == revision and status != stream.RUNNING:
            self._copyRevision = None
            if status == stream.DONE:
                self._copyThumbnail(path)

    def _showThumbnailPreview(self, path):
        pix = QPixmap(path) if path and os.path.exists(path) else QPixmap()
        if pix.isNull():
            self.streamThumbPreview.setPixmap(QPixmap())
            return
        self.streamThumbPreview.setPixmap(pix.scaled(
            self.streamThumbPreview.size(),
            Qt.AspectRatioMode.KeepAspectRatio,
            Qt.TransformationMode.SmoothTransformation,
        ))

    @staticmethod
    def _thumbnailErrorText(error):
        if error == stream.NO_ORG_THUMBNAIL:
            return QApplication.translate(
                "app", "配信団体サムネイルが登録されていません。")
        if error == stream.NO_BANNER:
            return QApplication.translate(
                "app", "No tournament banner available.")
        return QApplication.translate("app", "Error: ") + error

    def CopyStreamThumbnail(self):
        """Copy the most recently generated stream thumbnail to the
        clipboard. Generates one on demand if none exists yet, and copies it
        once it is done."""
        status, path, _error, revision = self._thumbnailState()
        if status == stream.RUNNING:
            self._copyRevision = revision
            return
        if path and os.path.exists(path):
            self._copyThumbnail(path)
            return
        StreamService.instance.GenerateThumbnail()
        status, _path, _error, revision = self._thumbnailState()
        if status == stream.RUNNING:
            self._copyRevision = revision

    def _copyThumbnail(self, path):
        try:
            image = QImage(path)
            if image.isNull():
                self.streamThumbPath.setText(QApplication.translate(
                    "app", "Failed to load thumbnail for copy."))
                return
            QApplication.clipboard().setImage(image)
            self.streamThumbPath.setText(
                QApplication.translate("app", "Copied to clipboard: ") + path)
        except Exception as e:
            logger.error(traceback.format_exc())
            self.streamThumbPath.setText(
                QApplication.translate("app", "Error: ") + str(e))
