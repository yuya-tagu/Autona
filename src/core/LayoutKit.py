"""The layout kit: "make a new design" (ADR-008 D2).

A new overlay (kind ``scoreboard`` / ``commentary`` / ``top8``) is made right
in ``layout/<folder>/``, where ``../include/`` resolves and the app's preview
and the OBS URL work as they are. Its files come from the kit,
``layout/include/kit/`` (KIT_DIR; ``include/`` is reserved, so the kit is
never listed):

* ``<kind>/index.html`` / ``index.css`` / ``index.js`` -- the kind's
  minimal sample on overlay contract 1 (``layout/include/autona.js``)
* ``<kind>/AI_PROMPT.md`` and ``CONTRACT.md`` -- generated from
  ``layout/include/overlay_contract.json`` by ``scripts/gen_layout_kit.py``
* ``AGENTS.md.tmpl`` / ``CLAUDE.md.tmpl`` -- the AI's instructions, renamed
  ``AGENTS.md`` / ``CLAUDE.md`` here (named so in the kit, the agents working
  on this repository would read them as their own)

and ``settings.json`` is written: the ``autona`` block with ``kind``,
``contract`` 1, ``displayName``, ``author`` and ``license``, the manifest an
import of ADR-007 D5 asks for, so a design handed to someone else is not
refused for its manifest. The generated files are copied without their first
line (GENERATED_MARK: "generated, do not edit" is the kit's, not the
operator's), and so is the AI text a page copies (AiPrompt).

The display name is free text (Japanese too), DISPLAY_NAME_MAX characters at
most once trimmed; the folder's name is the name's alone.

The folder is the kind's prefix (FOLDER_PREFIXES: the catalog's folder-name
convention, so Explorer sorts them together) and the name, which is NAME's
characters only (a folder name on every OS, and a URL path part as it is) and
at most NAME_MAX of them. Refused, with a reason (LayoutKitError.code), are a
folder the shipped release has or reserves (RESERVED_DIRS: an update would
write over it), and one that exists already, in any case (Windows does not
tell them apart). Nothing is overwritten: the folder is built in a work folder
beside it (LayoutCatalog.NEW_DESIGN_WORK_PREFIX, which the catalog never
lists) and renamed into place, tried again a few times while Windows holds a
file of it (an indexer, an antivirus); a folder of that name appearing
meanwhile is EXISTS. Each creation first removes the work folders a crash left
(older than STALE_WORK_SECONDS).

Writes go to that new folder alone, and only through ``NewDesign``. Its v1
route is WebAccess.SHELL (the shared view's own fetch): ``layout/`` is served
on the overlays' origin, so a layout's script must not make one.

Core module: no Qt, nothing done at import (tests/test_core_qt_free.py). The
folder is LayoutCatalog.Root() (or a given root).
"""

import errno
import json
import os
import re
import shutil
import threading
import time
import uuid

from loguru import logger

from . import LayoutCatalog

# Below the layout folder.
KIT_DIR = ("include", "kit")
SAMPLE_FILES = ("index.html", "index.css", "index.js")
AI_PROMPT_FILE = "AI_PROMPT.md"
CONTRACT_FILE = "CONTRACT.md"
# Kit file -> its name in a new design.
TEMPLATES = {"AGENTS.md.tmpl": "AGENTS.md", "CLAUDE.md.tmpl": "CLAUDE.md"}

# The kinds a new design may be, with the folder's prefix (the catalog's
# folder-name convention, LayoutCatalog._LEGACY_PREFIXES).
FOLDER_PREFIXES = {
    LayoutCatalog.KIND_SCOREBOARD: "scoreboard_",
    LayoutCatalog.KIND_COMMENTARY: "commentators_",
    LayoutCatalog.KIND_TOP8: "bracket_top8_",
}
KINDS = tuple(FOLDER_PREFIXES)

# The name after the prefix: ASCII letters, digits, "_" and "-", starting
# with a letter or a digit.
NAME_MAX = 40
NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]*")
# The display name (settings.json's displayName): any text, trimmed, at most
# this many characters; the name when none is given.
DISPLAY_NAME_MAX = 64

# The first line of the generated files (scripts/gen_layout_kit.py): dropped
# when they are copied into a design or onto the clipboard.
GENERATED_MARK = "<!-- Generated by scripts/gen_layout_kit.py"
GENERATED_FILES = ("AI_PROMPT.md", "CONTRACT.md")

# What a new design's settings.json says until the operator changes it
# (AGENTS.md tells them which keys they may change).
OVERLAY_CONTRACT = 1
DEFAULT_AUTHOR = "unknown"
DEFAULT_LICENSE = "All rights reserved"

# Folders under layout/ a new design may never be, in any case: the
# catalog's reserved ones and every folder the release ships (an update
# merges the release over the install and would write over a design there).
# tests/test_layout_kit.py holds this to the git-tracked folders.
RESERVED_DIRS = frozenset({
    "custom", "designer_runtime", "include", "icons",
    "bracket_top8", "camborder_Universal", "commentators", "h2h_record",
    "last_sets", "recent_sets", "result", "result_team", "result_team_split",
    "result_top16", "result_vertical", "result_vertical_geki",
    "scoreboard_Universal", "scoreboard_crewbattle", "scoreboard_simple",
    "scoreboard_team", "scoreboard_topleft", "thumbnail", "thumbnail_type_b",
    "tournament_history", "upset_factor", "winner_popup",
})

# LayoutKitError.code (the v1 refusal's error.reason).
BAD_KIND = "bad_kind"
BAD_NAME = "bad_name"
BAD_DISPLAY_NAME = "bad_display_name"
RESERVED = "reserved"
EXISTS = "exists"
KIT_MISSING = "kit_missing"
# Made and renamed into place, yet the catalog does not list it (the kit's
# files are broken): the folder is left for the operator to look at.
NOT_LISTED = "not_listed"
WRITE_FAILED = "write_failed"
CODES = (BAD_KIND, BAD_NAME, BAD_DISPLAY_NAME, RESERVED, EXISTS, KIT_MISSING,
         NOT_LISTED, WRITE_FAILED)

# The rename into place, while Windows holds a file of the work folder.
RENAME_ATTEMPTS = 5
RENAME_RETRY_SECONDS = 0.1
# A work folder older than this is a crashed creation's, removed by the next.
STALE_WORK_SECONDS = 3600

# One creation at a time: the check that the folder is free and the rename
# into it.
_lock = threading.Lock()


class LayoutKitError(Exception):
    """A refused or failed creation: ``code`` (the constants above).
    ``message`` is English, for the log; it may name a path, so the API
    answers the code and its own words."""

    def __init__(self, code, message):
        super().__init__(message)
        self.code = code
        self.message = message


def FolderName(kind, name):
    """The folder a design of ``kind`` named ``name`` goes in, or
    LayoutKitError BAD_KIND / BAD_NAME / RESERVED."""
    if not isinstance(kind, str) or kind not in FOLDER_PREFIXES:
        raise LayoutKitError(BAD_KIND, f"kind must be one of {KINDS}")
    if not isinstance(name, str) or not 1 <= len(name) <= NAME_MAX \
            or not NAME.fullmatch(name):
        raise LayoutKitError(
            BAD_NAME, f"the name must be 1 to {NAME_MAX} of A-Z a-z 0-9 _ -, "
                      "starting with a letter or a digit")
    folder = FOLDER_PREFIXES[kind] + name
    if folder.casefold() in {reserved.casefold() for reserved in RESERVED_DIRS}:
        raise LayoutKitError(RESERVED, f"{folder} is the release's")
    return folder


def DisplayName(displayName, name):
    """The display name a design gets: ``displayName`` trimmed, or ``name``
    when it is None or blank. LayoutKitError BAD_DISPLAY_NAME for one that
    is not a string, is longer than DISPLAY_NAME_MAX or holds a control
    character."""
    if displayName is None:
        return name
    if not isinstance(displayName, str):
        raise LayoutKitError(BAD_DISPLAY_NAME, "displayName must be text")
    text = displayName.strip()
    if not text:
        return name
    if len(text) > DISPLAY_NAME_MAX or any(
            ord(ch) < 32 or ord(ch) == 127 for ch in text):
        raise LayoutKitError(
            BAD_DISPLAY_NAME, f"displayName must be at most "
                              f"{DISPLAY_NAME_MAX} characters, no control "
                              "characters")
    return text


def NewDesign(kind, name, displayName=None, root=None):
    """Make a new design of ``kind`` (KINDS) named ``name`` (its folder,
    FolderName) shown as ``displayName`` (DisplayName) in
    ``layout/<FolderName>/`` from the kit, and return its catalog entry
    (LayoutCatalog's shape). LayoutKitError: BAD_KIND / BAD_NAME /
    BAD_DISPLAY_NAME / RESERVED / EXISTS (a folder of that name, in any case,
    is there), KIT_MISSING (the kit is not whole; nothing made), WRITE_FAILED
    (the folder could not be made; nothing is left of it), NOT_LISTED (made,
    but the catalog does not list it: left in place)."""
    folder = FolderName(kind, name)
    shown = DisplayName(displayName, name)
    base = _Base(root)
    kit = os.path.join(base, *KIT_DIR)
    sources = _KitSources(kit, kind)
    settings = {
        LayoutCatalog.METADATA_KEY: {
            "kind": kind,
            "contract": OVERLAY_CONTRACT,
            "displayName": shown,
            "author": DEFAULT_AUTHOR,
            "license": DEFAULT_LICENSE,
        },
    }
    _RemoveStaleWork(base)
    if _Taken(base, folder):
        raise LayoutKitError(EXISTS, f"{folder} exists")
    work = os.path.join(base, LayoutCatalog.NEW_DESIGN_WORK_PREFIX
                        + uuid.uuid4().hex)
    try:
        os.mkdir(work)
        for target, source in sources.items():
            if target in GENERATED_FILES:
                _CopyGenerated(source, os.path.join(work, target))
            else:
                shutil.copyfile(source, os.path.join(work, target))
        with open(os.path.join(work, LayoutCatalog.SETTINGS_FILE), "w",
                  encoding="utf-8", newline="\n") as f:
            json.dump(settings, f, ensure_ascii=False, indent=2)
            f.write("\n")
        with _lock:
            if _Taken(base, folder):
                raise LayoutKitError(EXISTS, f"{folder} exists")
            _RenameIntoPlace(work, os.path.join(base, folder))
    except LayoutKitError:
        _Discard(work)
        raise
    except OSError as e:
        _Discard(work)
        logger.warning(f"LayoutKit: could not make {folder}: "
                       f"{type(e).__name__}: {e}")
        raise LayoutKitError(WRITE_FAILED, f"could not make {folder}") from e
    logger.info(f"LayoutKit: made the {kind} design {folder}")
    entry = next((entry for entry in LayoutCatalog.Layouts([kind], base)
                  if entry["id"] == folder), None)
    if entry is None:
        # The kit's files make a listed design; a kit that does not is a
        # broken kit, and its design is left for the operator to look at.
        raise LayoutKitError(NOT_LISTED, f"{folder} is not listed")
    return entry


def AiPrompt(kind, root=None):
    """The kit's AI_PROMPT.md of ``kind``: what the list's "copy for an AI"
    puts on the clipboard, without its generated mark. LayoutKitError
    BAD_KIND / KIT_MISSING."""
    if not isinstance(kind, str) or kind not in FOLDER_PREFIXES:
        raise LayoutKitError(BAD_KIND, f"kind must be one of {KINDS}")
    path = os.path.join(_Base(root), *KIT_DIR, kind, AI_PROMPT_FILE)
    try:
        with open(path, encoding="utf-8") as f:
            return _WithoutMark(f.read())
    except OSError as e:
        raise LayoutKitError(KIT_MISSING, f"cannot read {path}: {e}") from e


# ── internals ────────────────────────────────────────────────────────────

def _Base(root):
    return os.path.abspath(root) if root else LayoutCatalog.Root()


def _KitSources(kit, kind):
    """{file name in the new design: its source in the kit}, every one
    there, else KIT_MISSING."""
    sources = {name: os.path.join(kit, kind, name) for name in SAMPLE_FILES}
    sources[AI_PROMPT_FILE] = os.path.join(kit, kind, AI_PROMPT_FILE)
    sources[CONTRACT_FILE] = os.path.join(kit, CONTRACT_FILE)
    for template, target in TEMPLATES.items():
        sources[target] = os.path.join(kit, template)
    missing = [name for name, path in sources.items()
               if not os.path.isfile(path)]
    if missing:
        raise LayoutKitError(KIT_MISSING, f"the kit lacks {missing}")
    return sources


def _Taken(base, folder):
    """Whether anything under ``base`` has the name ``folder``, in any
    case."""
    folded = folder.casefold()
    try:
        return any(name.casefold() == folded for name in os.listdir(base))
    except OSError as e:
        raise LayoutKitError(WRITE_FAILED, f"cannot list {base}: {e}") from e


def _Discard(work):
    shutil.rmtree(work, ignore_errors=True)


def _WithoutMark(text):
    """A generated file's text without its first line (GENERATED_MARK) and
    the blank lines after it; any other text as it is."""
    if not text.startswith(GENERATED_MARK):
        return text
    _first, _newline, rest = text.partition("\n")
    return rest.lstrip("\r\n")


def _CopyGenerated(source, target):
    # The text as it is but the mark: the line endings stay the kit's.
    with open(source, encoding="utf-8", newline="") as f:
        text = f.read()
    with open(target, "w", encoding="utf-8", newline="") as f:
        f.write(_WithoutMark(text))


def _RenameIntoPlace(work, target):
    """Rename ``work`` to ``target``. Not os.replace: a folder that appeared
    meanwhile is never replaced (EXISTS). A PermissionError (Windows: a file
    of the folder held a moment by an indexer or an antivirus) is tried
    again, RENAME_ATTEMPTS times in all."""
    for attempt in range(RENAME_ATTEMPTS):
        try:
            os.rename(work, target)
            return
        except FileExistsError as e:
            raise LayoutKitError(EXISTS, f"{target} appeared") from e
        except OSError as e:
            if e.errno in (errno.EEXIST, errno.ENOTEMPTY):
                raise LayoutKitError(EXISTS, f"{target} appeared") from e
            if not isinstance(e, PermissionError) \
                    or attempt == RENAME_ATTEMPTS - 1:
                raise
            time.sleep(RENAME_RETRY_SECONDS)


def _RemoveStaleWork(base):
    """Remove the work folders older than STALE_WORK_SECONDS: a creation
    that crashed. A newer one may be another creation's, under way."""
    now = time.time()
    try:
        names = os.listdir(base)
    except OSError:
        return
    for name in names:
        if not name.startswith(LayoutCatalog.NEW_DESIGN_WORK_PREFIX):
            continue
        path = os.path.join(base, name)
        try:
            stale = now - os.path.getmtime(path) > STALE_WORK_SECONDS
        except OSError:
            continue
        if stale and os.path.isdir(path) and not os.path.islink(path):
            logger.info(f"LayoutKit: removing a crashed creation's {name}")
            _Discard(path)
