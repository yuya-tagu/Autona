def test_a_failed_write_leaves_nothing_behind(root, monkeypatch):
    copied = []
    real = shutil.copyfile

    def failing(source, target):
        copied.append(target)
        if len(copied) == 3:
            raise OSError("disk full")
        return real(source, target)

    monkeypatch.setattr(LayoutKit.shutil, "copyfile", failing)
    with pytest.raises(LayoutKitError) as refused:
        LayoutKit.NewDesign("scoreboard", "mine", root=root)
    assert refused.value.code == LayoutKit.WRITE_FAILED
    assert _left(root) == []


