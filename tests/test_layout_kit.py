def _requests(api):
    return [
        lambda headers: api.post(CREATE, json={"kind": "scoreboard",
                                               "name": "mine"},
                                 headers=headers),
        lambda headers: api.get(_prompt("scoreboard"), headers=headers),
        lambda headers: api.post(REVEAL, json={"id": "scoreboard_mine"},
                                 headers=headers),
    ]


def test_a_page_of_this_origin_without_the_shells_secret_is_refused(api):
    # What a layout's script sends: same-origin, no secret (or a wrong one),
    # with the token too.
    token = WebAccess.RegenerateToken()
    same = {"Sec-Fetch-Site": "same-origin", "Sec-Fetch-Mode": "cors",
            "Sec-Fetch-Dest": "empty"}
    for headers in (same, dict(same, **{WebAccess.SHELL_HEADER: "x"}),
                    dict(same, **{"X-Autona-Token": token})):
        for send in _requests(api):
            refused = send(headers)
            assert refused.status_code == 403
            assert refused.get_json() == WebAccess.ErrorBody(
                WebAccess.SHELL_ONLY)
    assert _left(api.root) == []
    assert api.started == []


def test_another_computer_is_refused_even_with_the_secret(api):
    api.environ_base["REMOTE_ADDR"] = "192.168.1.20"
    for send in _requests(api):
        assert send(api.shell).status_code == 403
    assert _left(api.root) == []


