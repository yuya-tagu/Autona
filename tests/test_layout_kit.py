def test_a_broken_kit_and_a_failed_write_answer_their_reasons(
        api, monkeypatch):
    body = {"kind": "top8", "name": "mine"}
    missing = api.root / "include" / "kit" / "top8" / "index.js"
    kept = missing.read_bytes()
    missing.unlink()
    refused = api.post(CREATE, json=body, headers=api.shell)
    assert refused.status_code == 500
    assert refused.get_json()["error"]["reason"] == LayoutKit.KIT_MISSING
    missing.write_bytes(kept)

    def full(source, target):
        raise OSError("disk full")

    monkeypatch.setattr(LayoutKit.shutil, "copyfile", full)
    refused = api.post(CREATE, json=body, headers=api.shell)
    assert refused.status_code == 500
    assert refused.get_json()["error"]["reason"] == LayoutKit.WRITE_FAILED
    # Neither told a path.
    assert str(api.root) not in refused.get_data(as_text=True)
    assert _left(api.root) == []


