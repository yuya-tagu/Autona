    calls = []
    monkeypatch.setattr(LayoutCatalog, "subprocess", SimpleNamespace(
        Popen=lambda args, **kwargs: calls.append(args)))
    monkeypatch.setattr(LayoutCatalog.sys, "platform", "win32")
    monkeypatch.setenv("WINDIR", r"C:\Windows")
    return calls


