def _left(root):
    return sorted(name for name in os.listdir(root) if name != "include")


def test_a_new_design_is_made_from_the_kit_and_listed(root):
    entry = LayoutKit.NewDesign("commentary", "Duo", root=root)

    assert entry == {"id": "commentators_Duo", "kind": "commentary",
                     "displayName": "Duo", "format": None, "game": None,
                     "entry": "index.html", "contract": 1}
    folder = root / "commentators_Duo"
    assert sorted(os.listdir(folder)) == sorted([
        "index.html", "index.css", "index.js", "settings.json", "AGENTS.md",
        "CLAUDE.md", "AI_PROMPT.md", "CONTRACT.md"])
    for name in ("index.html", "index.css", "index.js"):
        assert (folder / name).read_bytes() == (
            KIT / "commentary" / name).read_bytes()
    assert (folder / "AGENTS.md").read_bytes() == (
        KIT / "AGENTS.md.tmpl").read_bytes()
    assert (folder / "CLAUDE.md").read_bytes() == (
        KIT / "CLAUDE.md.tmpl").read_bytes()
    # The generated files without their "generated, do not edit" line.
    for name, source in (("AI_PROMPT.md", KIT / "commentary" / "AI_PROMPT.md"),
                         ("CONTRACT.md", KIT / "CONTRACT.md")):
        copied = (folder / name).read_bytes().decode("utf-8")
        kit = source.read_bytes().decode("utf-8")
        assert not copied.startswith(LayoutKit.GENERATED_MARK)
        assert copied == LayoutKit._WithoutMark(kit) != kit
    # The manifest an import asks for (ADR-007 D5): kind, contract, a name,
    # an author and a license.
    settings = json.loads((folder / "settings.json").read_text(
        encoding="utf-8"))
    assert settings == {"autona": {
        "kind": "commentary", "contract": 1, "displayName": "Duo",
        "author": LayoutKit.DEFAULT_AUTHOR,
        "license": LayoutKit.DEFAULT_LICENSE}}
    assert LayoutKit.OVERLAY_CONTRACT in LayoutCatalog.OVERLAY_CONTRACTS
    # Listed now, with no restart, under its kind; the work folder is gone.
    assert [e["id"] for e in LayoutCatalog.Layouts(["commentary"], root)] == [
        "commentators_Duo"]
    assert _left(root) == ["commentators_Duo"]


