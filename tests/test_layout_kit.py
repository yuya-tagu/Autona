@needs_node
def test_the_samples_draw_what_the_view_holds(tmp_path):
    board, commentary, top8 = run_scenarios(tmp_path, [
        _scenario("scoreboard", "singles"),
        _scenario("commentary", "singles"),
        _scenario("top8", "singles"),
    ])
    view = board["calls"][-1]["view"]
    out = board["out"]
    assert out["p1-name"]["text"] == (view["board"]["p1"]["teamName"]
                                      or view["board"]["p1"]["name"]) != ""
    assert out["p2-score"]["text"] == str(view["board"]["p2"]["score"] or 0)
    assert out["round"]["text"] == view["board"]["round"]
    assert out["p1-character"]["src"] == view["board"]["p1"]["character"]["icon"]

    view = commentary["calls"][-1]["view"]
    cards = commentary["out"]["casters"]["children"]
    assert len(cards) == len(view["commentary"]) > 0
    for card, caster in zip(cards, view["commentary"]):
        assert caster["name"] in _texts(card)

    view = top8["calls"][-1]["view"]
    shown = _texts(top8["out"]["winners"]) + _texts(top8["out"]["losers"])
    for matchId, match in view["top8"]["matches"].items():
        # The reset shows only when it is played.
        played = matchId != "gf_reset" or match["active"]
        assert (match["name"] in shown) == played, matchId
    assert top8["out"]["phase"]["text"] == view["top8"]["phaseLabel"]

    # A match with both players known and not finished is marked as being
    # played; an undecided player shows TBD.
    cards = [card for side in ("winners", "losers")
             for column in top8["out"][side]["children"]
             for card in column["children"]]
    live = [m for m in view["top8"]["matches"].values()
            if m["p1"]["slot"] is not None and m["p2"]["slot"] is not None
            and not m["finished"]]
    assert sum("live" in card["classes"] for card in cards) == len(live)
    if any(m[side]["slot"] is None for m in view["top8"]["matches"].values()
           for side in ("p1", "p2")):
        assert "TBD" in shown


