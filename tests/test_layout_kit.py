# A page as far as the kit's samples can tell: getElementById finds the ids
# index.html has (null for any other: a TypeError the onUpdate's error
# report shows), elements keep their text, attributes, classes and children.
_DOM = r"""
(function () {
  var ids = __IDS__;
  function make(tag) {
    var node = {
      tagName: tag, className: "", hidden: false, children: [],
      attributes: {}, textContentValue: "",
      style: {props: {}, setProperty: function (k, v) { this.props[k] = v; }},
      classList: {set: {}, toggle: function (name, on) {
        if (on === undefined) on = !this.set[name];
        if (on) this.set[name] = true; else delete this.set[name];
        return on; }},
      setAttribute: function (k, v) { this.attributes[k] = String(v); },
      removeAttribute: function (k) { delete this.attributes[k]; },
      appendChild: function (child) { this.children.push(child); return child; },
      replaceChildren: function () { this.children = []; },
    };
    Object.defineProperty(node, "textContent", {
      get: function () { return this.textContentValue; },
      set: function (v) { this.textContentValue = String(v); this.children = []; },
    });
    return node;
  }
  var nodes = {};
  ids.forEach(function (id) { nodes[id] = make("div"); });
  document.getElementById = function (id) {
    return Object.prototype.hasOwnProperty.call(nodes, id) ? nodes[id] : null;
  };
  document.createElement = make;
  document.documentElement = make("html");
  function dump(node) {
    return {text: node.textContentValue, hidden: node.hidden,
            src: node.attributes.src || "", classes: Object.keys(node.classList.set),
            children: node.children.map(dump)};
  }
  window.__dump = function () {
    var out = {};
    Object.keys(nodes).forEach(function (id) { out[id] = dump(nodes[id]); });
    out[":root"] = document.documentElement.style.props;
    return out;
  };
})();
"""


def _ids(kind):
    html = (KIT / kind / "index.html").read_text(encoding="utf-8")
    return re.findall(r'\bid="([^"]+)"', html)


def _scenario(kind, sample, search=""):
    return {
        "kind": kind,
        "search": search,
        "pathname": f"/layout/{LayoutKit.FOLDER_PREFIXES[kind]}mine/index.html",
        "layout": _DOM.replace("__IDS__", json.dumps(_ids(kind))),
        "afterAutona": (KIT / kind / "index.js").read_text(encoding="utf-8"),
        "steps": [
            {"state": json.loads((SAMPLES / f"{sample}.json")
                                 .read_text(encoding="utf-8")), "revision": 1},
            {"run": "__out = __dump();"},
        ],
    }


def _texts(node):
    return [node["text"]] + [text for child in node["children"]
                             for text in _texts(child)]


